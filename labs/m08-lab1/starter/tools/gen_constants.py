"""Write a Python module of string constants from a CSV file.

Usage: gen_constants.py INPUT.csv OUTPUT.py

Each CSV row is NAME,value (with a header row). Rows are sorted by name, so the
output does not depend on the order of the CSV.
"""

import csv
import os
import sys


def render(rows: list[tuple[str, str]], source: str) -> str:
    """Return the text of the generated module."""
    lines = [f'"""Generated by //tools:gen_constants from {source}. Do not edit."""', ""]
    lines += [f'{name.upper()} = "{value}"' for name, value in sorted(rows)]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> None:
    src, out = argv[1], argv[2]
    with open(src, newline="") as f:
        reader = csv.reader(f)
        next(reader)  # header
        rows = [(name, value) for name, value in reader]
    with open(out, "w") as f:
        f.write(render(rows, os.path.basename(src)))


if __name__ == "__main__":
    main(sys.argv)
