"""Turn the product catalog CSV into a Python module.

Usage: catalog_gen.py INPUT.csv OUTPUT.py

The CSV has a header row and then SKU,name,price_cents rows. The module defines
PRODUCTS, a dict from SKU to (name, price in cents), sorted by SKU so the output
does not depend on the order of the CSV.
"""

import csv
import os
import sys


def render(rows: list[tuple[str, str, int]], source: str) -> str:
    """Return the text of the generated module."""
    lines = [
        f'"""Generated by //tools/catalog_gen from {source}. Do not edit."""',
        "",
        "PRODUCTS = {",
    ]
    lines += [f'    "{sku}": ("{name}", {cents}),' for sku, name, cents in sorted(rows)]
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> None:
    src, out = argv[1], argv[2]
    with open(src, newline="", encoding="utf-8") as f:
        reader = csv.reader(f)
        next(reader)  # header
        rows = [(sku, name, int(cents)) for sku, name, cents in reader]
    with open(out, "w", encoding="utf-8") as f:
        f.write(render(rows, os.path.basename(src)))


if __name__ == "__main__":
    main(sys.argv)
